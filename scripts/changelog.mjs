// CHANGELOG.md is generated from Conventional Commits, never written by hand (P7-07).
//   npm run changelog                  rewrite CHANGELOG.md from the release tags
//   npm run changelog -- --next        also add the package.json version, before its tag exists
//   node scripts/changelog.mjs --check fail when CHANGELOG.md differs (a gate step)
// Each section is the release-note draft of the built CLI for one tag range, so
// the changelog and the GitHub Release notes are the same text. The check also
// accepts the file with the untagged package version, which is what a release
// pull request contains before its tag is created.
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HEADER =
  '# Changelog\n\nAll notable changes to wholeloop, generated from Conventional Commits by `npm run changelog`. Do not edit this file by hand; versions follow the policy in [releasing](./docs/contributing/releasing.md#versions).\n'

const option = (name) => {
  const index = process.argv.indexOf(name)
  return index > 0 ? process.argv[index + 1] : undefined
}
const root = resolve(option('--root') ?? dirname(dirname(fileURLToPath(import.meta.url))))
const cli = resolve(option('--cli') ?? join(root, 'dist/wl.mjs'))
const run = (command, args) => {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  })
  if (
    result.status !== 0 &&
    !(command === process.execPath && result.stdout.trim().startsWith('{'))
  )
    throw new Error(`${args.slice(0, 2).join(' ')} failed`)
  return result.stdout
}
const semver = /^v((?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?)$/
// Semantic-version precedence: a pre-release sorts before its final version.
// git's v:refname order puts 1.0.0 before 1.0.0-rc.1, so it is not used.
export function compareVersions(a, b) {
  const [coreA, preA] = a.split(/-(.*)/s)
  const [coreB, preB] = b.split(/-(.*)/s)
  const core = (value) => value.split('.').map(Number)
  const [x, y] = [core(coreA), core(coreB)]
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]
  if (!preA || !preB) return preA ? -1 : preB ? 1 : 0
  const [p, q] = [preA.split('.'), preB.split('.')]
  for (let i = 0; i < Math.max(p.length, q.length); i++) {
    if (p[i] === undefined) return -1
    if (q[i] === undefined) return 1
    const numeric = /^\d+$/.test(p[i]) && /^\d+$/.test(q[i])
    const order = numeric ? Number(p[i]) - Number(q[i]) : p[i].localeCompare(q[i])
    if (order) return order
  }
  return 0
}

// The release a version's notes start from. A final version starts at the
// previous final version, so 1.0.0 describes everything since the last stable
// release rather than only the fixes after its last candidate; a pre-release
// starts at the version just before it. Rejected: starting every version at
// the previous tag, which left the 1.0.0 notes with a single entry.
export function previousVersion(version, versions) {
  const final = !version.includes('-')
  return versions
    .filter((other) => compareVersions(other, version) < 0 && !(final && other.includes('-')))
    .sort(compareVersions)
    .at(-1)
}

// Headings carry no date: the untagged section a release pull request adds must
// match, byte for byte, the section generated once its tag exists, or the gate
// would fail on the default branch after every release. The GitHub Release
// records when each version was published.
function section(from, to, version) {
  const notes = JSON.parse(
    run(process.execPath, [
      cli,
      'release',
      'notes',
      ...(from ? ['--from', from] : ['--initial']),
      '--to',
      to,
      '--version',
      version,
      '--json',
    ]),
  )
  // The draft opens with its own title; the changelog gives each release a dated heading.
  const body = notes.markdown.replace(/^# .*\n+/, '').replace(/^## /gm, '### ')
  return `## ${version}\n\n${body.trimEnd()}\n`
}

export function changelog(withNext) {
  const tags = run('git', ['tag', '--list', 'v*'])
    .split('\n')
    .filter((tag) => semver.test(tag))
    .sort((a, b) => compareVersions(a.slice(1), b.slice(1)))
  const versions = tags.map((tag) => tag.slice(1))
  const start = (version) => {
    const previous = previousVersion(version, versions)
    return previous ? `v${previous}` : undefined
  }
  const sections = versions.map((version) => section(start(version), `v${version}`, version))
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  if (withNext && !versions.includes(version))
    sections.push(section(start(version), 'HEAD', version))
  return `${HEADER}\n${sections.length ? sections.reverse().join('\n') : 'No release has been tagged yet.\n'}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = join(root, 'CHANGELOG.md')
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(file, 'utf8')
    } catch {}
    if (current !== changelog(false) && current !== changelog(true)) {
      console.error(
        'changelog: CHANGELOG.md differs from the generated text; run npm run changelog',
      )
      process.exitCode = 1
    } else console.log('changelog: CHANGELOG.md matches the release tags')
  } else {
    writeFileSync(file, changelog(process.argv.includes('--next')))
    console.log('changelog: CHANGELOG.md written')
  }
}
